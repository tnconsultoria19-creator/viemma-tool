/**
 * Merges saved trip/workspace experience library items with the full South African master catalogue
 * so that older saved trips automatically gain access to all new catalogue entries without losing
 * user edits or custom experiences.
 */
export function mergeWithMasterCatalogue(saved?: ExperienceLibraryItem[]): ExperienceLibraryItem[] {
  if (!saved || saved.length === 0) return DEFAULT_EXPERIENCES;
  const byId = new Map<string, ExperienceLibraryItem>();
  for (const def of DEFAULT_EXPERIENCES) {
    byId.set(def.id, def);
  }
  for (const item of saved) {
    const existingDef = byId.get(item.id);
    if (existingDef) {
      byId.set(item.id, {
        ...existingDef,
        ...item,
        aliases: item.aliases?.length ? item.aliases : existingDef.aliases,
        province: item.province || existingDef.province,
        town: item.town || existingDef.town,
        subcategory: item.subcategory || existingDef.subcategory,
        activityType: item.activityType || existingDef.activityType,
        sourceUrl: item.sourceUrl || existingDef.sourceUrl,
      });
    } else {
      byId.set(item.id, item);
    }
  }
  return Array.from(byId.values());
}

/**
 * Merges saved destination library items with the master destination defaults.
 */
export function mergeWithMasterDestinations(saved?: DestinationLibraryItem[]): DestinationLibraryItem[] {
  if (!saved || saved.length === 0) return DEFAULT_DESTINATIONS;
  const byId = new Map<string, DestinationLibraryItem>();
  for (const def of DEFAULT_DESTINATIONS) {
    byId.set(def.id, def);
  }
  for (const item of saved) {
    byId.set(item.id, item);
  }
  return Array.from(byId.values());
}
